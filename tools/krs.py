FILE_BLOCK = re.compile(r"^=== FILE: (\S+) ===\n(.*?)\n=== END FILE ===", re.S | re.M)


def apply_reply(task: dict, ws: Path, reply: str) -> tuple[list[str], list[str]]:
    allowed = task.get("scope", {}).get("write", [])
    written, refused = [], []
    for rel, body in FILE_BLOCK.findall(reply):
        body = re.sub(r"^```\w*\n", "", body)
        body = re.sub(r"\n```\s*$", "", body)
        if not matches(rel, allowed) or ".." in rel:
            refused.append(rel)
            continue
        (ws / rel).parent.mkdir(parents=True, exist_ok=True)
        (ws / rel).write_text(body.rstrip("\n") + "\n")
        written.append(rel)
    return written, refused


def chat(endpoint: str, model: str, messages: list[dict], max_tokens: int) -> str:
    body = json.dumps({"model": model, "messages": messages, "temperature": 0.2, "max_tokens": max_tokens}).encode()
    req = urllib.request.Request(endpoint.rstrip("/") + "/chat/completions", data=body,
                                 headers={"Content-Type": "application/json"})
    if os.environ.get("KRS_API_KEY"):
        req.add_header("Authorization", f"Bearer {os.environ['KRS_API_KEY']}")
    with urllib.request.urlopen(req, timeout=1800) as resp:
        return json.loads(resp.read())["choices"][0]["message"]["content"]


def cmd_work(args):
    task = get_task(args.task)
    ws = workspace_path(task["id"])
    if not ws.exists():
        cmd_workspace(argparse.Namespace(task=task["id"]))
    system = WORKER_PROMPT.read_text()
    brief = build_brief(task, args.budget or task.get("context", {}).get("budget", 12000), for_work=True)
    feedback, last_reply = None, None
    for round_no in range(1, args.rounds + 1):
        # Only the brief, the latest attempt and its feedback: old rounds are dropped
        # so the prompt stays within a small model's context.
        messages = [{"role": "system", "content": system}, {"role": "user", "content": brief}]
        if last_reply:
            messages += [{"role": "assistant", "content": last_reply},
                         {"role": "user", "content": f"The checks rejected that attempt:\n\n{feedback}\n\n"
                                                     "Reply with complete corrected files in the same format."}]
        print(f"round {round_no}: asking {args.model} (~{est_tokens(json.dumps(messages))} prompt tokens)")
        last_reply = chat(args.endpoint, args.model, messages, args.max_tokens)
        written, refused = apply_reply(task, ws, last_reply)
        print(f"  wrote {written or 'nothing'}" + (f"; refused {refused}" if refused else ""))
        if not written:
            feedback = ("No files were found in your reply. Use exactly:\n=== FILE: path ===\n<full contents>\n"
                        "=== END FILE ===" + (f"\nThese paths are outside your scope: {refused}" if refused else ""))
            continue
        verdict = cmd_check(argparse.Namespace(task=task["id"], dir=None, feedback=False))
        if verdict["verdict"] == "ACCEPT":
            print(f"worker produced an accepted change in {round_no} rounds; review it, then `krs accept {task['id']}`")
            return
        feedback = "\n".join(f"- {r}" for r in verdict["reasons"]) + "\n\n" + verdict["feedback"][:6000]
    print(f"no accepted change after {args.rounds} rounds; see .cache/krs/runs/{task['id']}/latest.json")


