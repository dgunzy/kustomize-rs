#!/usr/bin/env python3
"""krs: delegate kustomize-rs tasks to a worker, check the result, accept or reject.

The lead (a strong model or a human) plans; workers (small models, subagents,
other people) implement one task at a time in an isolated copy of the repo.
Nothing here writes to git. See delegation/README.md for the protocol.

Commands (all print short output; details go to files under .cache/krs/):

  status                     one-screen overview: score, tasks, what's ready
  next [--owner lead|worker] ready tasks (dependencies done), best first
  show TASK                  the task definition
  upstream                   cache upstream sources (kustomize, fluxcd/pkg) at the pinned commits
  brief TASK [--budget N]    a self-contained, token-budgeted context packet for a worker
  workspace TASK             fresh isolated copy at .cache/work/TASK (prints its path)
  check TASK                 run every gate in the workspace; verdict ACCEPT or REJECT
  accept TASK                copy an accepted workspace into the repo, update the baseline, mark done
  reject TASK [--reason R]   log the rejection and drop the workspace
  work TASK --endpoint URL --model M [--rounds N]
                             run a worker loop against an OpenAI-compatible chat API

Python 3.11+ (tomllib), standard library only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import difflib
import fnmatch
import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tasks"
CACHE = ROOT / ".cache"
KRS = CACHE / "krs"
WORK = CACHE / "work"
UPSTREAM = CACHE / "upstream"
FIXTURES = ROOT / "tests/fixtures/krusty"
WORKER_PROMPT = ROOT / "delegation/prompts/worker.md"

# Directories never copied into a workspace or compared.
SKIP_DIRS = {".git", "target", ".cache", "node_modules", "__pycache__"}
# A worker may never change these unless its task scope lists the exact path.
PROTECTED = [
    "tests/fixtures/**", "conformance/**", "tools/**", "tasks/**", "delegation/**",
    "scripts/**", ".github/**", ".claude/**", "AGENTS.md", "CLAUDE.md", "SPEC.md",
    "ROADMAP.md", "NOTICE", "LICENSE", "Cargo.toml", "Cargo.lock", "clippy.toml",
    "deny.toml", "justfile", "tests/fixture_leaks.rs", "tests/conformance/**",
]
# Never counted as a worker's change: regenerated by the gates, or owned by the
# lead (task files track status in the repo, not the workspace).
IGNORED_CHANGES = {"conformance/STATUS.md"}
IGNORED_PREFIXES = ("tasks/",)

SOURCES = {
    "kustomize": ("kubernetes-sigs/kustomize", FIXTURES / "UPSTREAM_COMMIT", ("api/", "kyaml/")),
    "fluxpkg": ("fluxcd/pkg", ROOT / "tests/fixtures/flux/UPSTREAM_COMMIT", ("kustomize/", "envsubst/", "sourceignore/")),
}


# ---------------------------------------------------------------- helpers

def die(msg: str, code: int = 1):
    print(f"krs: {msg}", file=sys.stderr)
    sys.exit(code)


def est_tokens(text: str) -> int:
    """Rough token estimate (code averages ~3.5 chars per token)."""
    return int(len(text) / 3.5) + 1


def load_tasks() -> dict[str, dict]:
    tasks = {}
    for path in sorted(TASKS.glob("*.toml")):
        try:
            with path.open("rb") as f:
                t = tomllib.load(f)
        except tomllib.TOMLDecodeError as e:
            die(f"{path.relative_to(ROOT)}: {e}")
        t["_path"] = path
        tasks[t["id"]] = t
    return tasks


def get_task(task_id: str) -> dict:
    tasks = load_tasks()
    if task_id not in tasks:
        close = [t for t in tasks if task_id.lower() in t.lower()]
        die(f"no task {task_id!r}" + (f"; did you mean {', '.join(close)}?" if close else ""))
    return tasks[task_id]


def set_status(task: dict, status: str):
    path: Path = task["_path"]
    text = path.read_text()
    text, n = re.subn(r'(?m)^status\s*=\s*".*"$', f'status = "{status}"', text, count=1)
    if n != 1:
        die(f"{path}: no status line")
    path.write_text(text)


def ready(task: dict, tasks: dict) -> bool:
    return task.get("status") == "todo" and all(
        tasks.get(d, {}).get("status") == "done" for d in task.get("depends_on", [])
    )


def matches(path: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatch(path, p) or path == p for p in patterns)


def run(cmd: list[str], cwd: Path, log: Path | None = None, env: dict | None = None) -> tuple[int, str]:
    full_env = {**os.environ, **(env or {})}
    p = subprocess.run(cmd, cwd=cwd, env=full_env, capture_output=True, text=True)
    out = p.stdout + p.stderr
    if log:
        log.write_text(out)
    return p.returncode, out


def tree_files(base: Path) -> dict[str, str]:
    """Relative path -> sha256 for every file outside SKIP_DIRS."""
    out = {}
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            p = Path(dirpath) / name
            rel = p.relative_to(base).as_posix()
            out[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


def base_path(work: Path) -> Path:
    return KRS / "base" / f"{work.name}.json"


def base_files(work: Path) -> dict[str, str]:
    """The workspace's snapshot at creation: what the worker started from."""
    path = base_path(work)
    if not path.exists():
        die(f"no base snapshot for {work}; recreate it with `krs workspace {work.name}`")
    return json.loads(path.read_text())


def changed_files(work: Path) -> dict[str, str]:
    """The worker's changes: workspace vs its base snapshot (not the live repo,
    which the lead may have changed meanwhile). path -> added|modified|deleted."""
    a, b = base_files(work), tree_files(work)
    out = {}
    for rel in sorted(set(a) | set(b)):
        if rel in IGNORED_CHANGES or rel.startswith(IGNORED_PREFIXES):
            continue
        if rel not in a:
            out[rel] = "added"
        elif rel not in b:
            out[rel] = "deleted"
        elif a[rel] != b[rel]:
            out[rel] = "modified"
    return out


def workspace_path(task_id: str) -> Path:
    return WORK / task_id


def cargo_env(cwd: Path) -> dict:
    """Each source tree gets its own target dir. Sharing one across trees lets cargo
    reuse a binary built from another tree (its fingerprints are mtime-based), so a
    check could test the wrong code. Workspaces keep theirs under target/krs/."""
    env = {"CARGO_TERM_COLOR": "never"}
    if cwd.resolve() != ROOT:
        env["CARGO_TARGET_DIR"] = str(ROOT / "target/krs" / cwd.name)
    return env


# ---------------------------------------------------------------- upstream

def ensure_upstream(name: str) -> Path:
    repo, commit_file, keep = SOURCES[name]
    commit = commit_file.read_text().strip()
    dest = UPSTREAM / name
    stamp = dest / ".commit"
    if stamp.exists() and stamp.read_text().strip() == commit:
        return dest
    url = f"https://codeload.github.com/{repo}/tar.gz/{commit}"
    print(f"downloading {repo}@{commit[:12]} ...", file=sys.stderr)
    with urllib.request.urlopen(url, timeout=300) as resp:
        data = resp.read()
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            parts = member.name.split("/", 1)
            if len(parts) < 2 or not member.isfile() or not parts[1].startswith(keep):
                continue
            target = dest / parts[1]
            target.parent.mkdir(parents=True, exist_ok=True)
            src = tar.extractfile(member)
            if src:
                target.write_bytes(src.read())
    stamp.write_text(commit + "\n")
    return dest


def go_symbols(text: str, names: list[str]) -> str:
    """Extract top-level Go declarations (with their doc comments) by name.

    Every declaration with the name is included: Go files often have both
    `type Filter` and a `Filter` method.
    """
    lines = text.splitlines()
    out = []
    for name in names:
        pat = re.compile(rf"^(func (\([^)]*\) )?{re.escape(name)}\b|type {re.escape(name)}\b|(var|const) {re.escape(name)}\b)")
        found = False
        for i, line in enumerate(lines):
            if not pat.match(line):
                continue
            found = True
            start = i
            while start > 0 and lines[start - 1].startswith("//"):
                start -= 1
            end = i
            if line.rstrip().endswith(("{", "(")):
                closer = "}" if line.rstrip().endswith("{") else ")"
                while end < len(lines) and lines[end] != closer:
                    end += 1
            out.append("\n".join(lines[start:end + 1]))
        if not found:
            out.append(f"// (symbol {name} not found)")
    return "\n\n".join(out)


def upstream_ref(ref: str) -> tuple[str, str]:
    """'kustomize:api/filters/x.go#A,B' -> (title, source text)."""
    source, _, rest = ref.partition(":")
    path, _, symbols = rest.partition("#")
    base = ensure_upstream(source)
    file = base / path
    if not file.exists():
        return ref, f"(missing upstream file {path})"
    text = file.read_text()
    if symbols:
        text = go_symbols(text, [s.strip() for s in symbols.split(",")])
    return ref, text


# ---------------------------------------------------------------- conformance

def case_dirs(filters: list[str]) -> list[Path]:
    out = []
    for case in sorted(FIXTURES.rglob("case.yaml")):
        cid = case.parent.relative_to(FIXTURES).as_posix()
        if any(cid.startswith(f) or f in cid for f in filters):
            out.append(case.parent)
    return out


def last_results() -> dict | None:
    path = KRS / "results.json"
    return json.loads(path.read_text()) if path.exists() else None


def conformance(cwd: Path, out_json: Path, check_regressions: bool = True) -> tuple[int, str]:
    cmd = ["cargo", "test", "-q", "--test", "conformance", "--", "--json", str(out_json), "--no-status"]
    if check_regressions:
        cmd.append("--check-regressions")
    return run(cmd, cwd, env=cargo_env(cwd))


# ---------------------------------------------------------------- commands

def cmd_status(args):
    tasks = load_tasks()
    results = last_results()
    if results:
        s = results["summary"]
        print(f"conformance: {s['pass']}/{s['inScope']} pass, {s['unimplemented']} unimplemented, "
              f"{s['fail']} fail, {s['deferred']} deferred  (from .cache/krs/results.json)")
    else:
        status_md = ROOT / "conformance/STATUS.md"
        line = next((l for l in status_md.read_text().splitlines() if l.startswith("**")), "") if status_md.exists() else ""
        print(f"conformance: {line.strip('*') or 'no results yet (run `just conformance`)'}  (from STATUS.md)")
    by = {}
    for t in tasks.values():
        by.setdefault(t.get("status", "todo"), []).append(t["id"])
    for status in ("in-progress", "todo", "blocked", "done"):
        if status in by:
            print(f"{status:>11}: {', '.join(by[status])}")
    ready_ids = [t["id"] for t in sorted(tasks.values(), key=lambda t: t.get("order", 999)) if ready(t, tasks)]
    print(f"      ready: {', '.join(ready_ids) or '(none)'}")
    for ws in sorted(WORK.glob("*")) if WORK.exists() else []:
        print(f"  workspace: {ws.relative_to(ROOT)}")


def cmd_next(args):
    tasks = load_tasks()
    rows = [t for t in tasks.values() if ready(t, tasks) and (not args.owner or t.get("owner") == args.owner)]
    rows.sort(key=lambda t: t.get("order", 999))
    if not rows:
        print("no ready tasks")
    for t in rows:
        print(f"{t['id']:<28} owner={t.get('owner','?'):<6} difficulty={t.get('difficulty','?')}  {t['title']}")


def cmd_show(args):
    print(get_task(args.task)["_path"].read_text())


def cmd_upstream(args):
    for name in SOURCES:
        print(f"{name}: {ensure_upstream(name).relative_to(ROOT)}")


def rust_outline(text: str) -> str:
    """A read-only Rust file as its API: doc comments, signatures and type
    definitions, with function bodies elided and the test module dropped."""
    text = text.split("\n#[cfg(test)]", 1)[0]
    out, depth, skip_until = [], 0, None
    for line in text.splitlines():
        stripped = line.strip()
        opens, closes = line.count("{"), line.count("}")
        if skip_until is not None:
            depth += opens - closes
            if depth <= skip_until:
                skip_until = None
            continue
        if re.match(r"(pub(\(crate\))? )?(const )?(async )?(unsafe )?fn ", stripped) and stripped.endswith("{"):
            out.append(line[: len(line) - len(line.lstrip())] + stripped[:-1].rstrip() + " { ... }")
            skip_until = depth
            depth += opens - closes
            if depth <= skip_until:
                skip_until = None
            continue
        depth += opens - closes
        out.append(line)
    return "\n".join(out) + "\n"


def build_brief(task: dict, budget: int, for_work: bool = False) -> str:
    ctx, scope, acc = task.get("context", {}), task.get("scope", {}), task.get("accept", {})
    must: list[str] = []
    must.append(f"# Task {task['id']}: {task['title']}\n")
    must.append(task.get("summary", "").strip() + "\n")
    if task.get("notes"):
        must.append("## Lead's notes\n\n" + task["notes"].strip() + "\n")
    crit = ["`just ci` passes (fmt, clippy, unit tests, fixture-leak check)",
            "no conformance regressions against conformance/baseline.txt"]
    for t in acc.get("tests", []):
        crit.append(f"unit tests matching `{t}` exist and pass")
    for c in acc.get("cases", []):
        crit.append(f"every upstream case under `{c}` passes")
    if acc.get("min_new_passes"):
        crit.append(f"at least {acc['min_new_passes']} upstream cases newly pass")
    must.append("## Done when\n\n" + "\n".join(f"- {c}" for c in crit) + "\n")
    must.append("## You may only change\n\n" + "\n".join(f"- `{p}`" for p in scope.get("write", [])) + "\n")
    if ctx.get("upstream"):
        must.append("New Rust files that port upstream logic start with the attribution header:\n\n"
                    "```rust\n// Portions of this file are ported from kustomize <upstream path>,\n"
                    "// Copyright The Kubernetes Authors, licensed under Apache-2.0.\n"
                    "// Modified: translated from Go to Rust and adapted to this crate.\n```\n")
    if not for_work:
        must.append("## Rules\n\n" + WORKER_PROMPT.read_text().split("## Rules", 1)[-1].split("\n## ", 1)[0].strip() + "\n")

    optional: list[tuple[str, str]] = []
    # Priority order, most useful first: the files to edit (whole, since the
    # worker sends them back complete), upstream Go, upstream unit tables,
    # read-only Rust as outlines, then example cases.
    write = [p for p in scope.get("write", []) if "*" not in p]
    for rel in write:
        p = ROOT / rel
        if p.is_file():
            optional.append((f"Rust (edit): {rel}", f"```rust\n{p.read_text()}```\n"))
        else:
            optional.append((f"Rust (edit): {rel}", "(does not exist yet; create it)\n"))
    for ref in ctx.get("upstream", []):
        title, text = upstream_ref(ref)
        optional.append((f"Upstream: {title}", f"```go\n{text}\n```\n"))
    # Upstream's own unit tables for the filter being ported.
    for unit in ctx.get("units", []):
        path = ROOT / "tests/fixtures/units" / f"{unit}.json"
        if not path.exists():
            continue
        doc = json.loads(path.read_text())
        cases = doc.get("cases", [])
        limit = ctx.get("max_unit_cases", 6)
        parts = [f"{len(cases)} cases from `{doc.get('upstream')}`, extracted to "
                 f"`tests/fixtures/units/{unit}.json` (keys: name, YAML fields, and `go` = the "
                 "case's filter settings in Go). Port them as a table-driven unit test that reads "
                 "the file with `include_str!` (see `upstream_merge2_tables` in src/smp.rs); skip a "
                 "case only with a comment saying why it can't apply.\n"]
        for case in cases[:limit]:
            parts.append(f"### {case.get('name') or case.get('description')}\n")
            if case.get("go"):
                parts.append(f"```go\n{case['go']}\n```\n")
            for key, value in case.items():
                if key not in ("name", "description", "go", "file") and isinstance(value, str):
                    parts.append(f"{key}:\n```yaml\n{value}```\n")
        if len(cases) > limit:
            parts.append(f"... and {len(cases) - limit} more in the file.\n")
        optional.append((f"Upstream unit table: {unit}", "".join(parts)))
    for rel in ctx.get("read", []):
        p = ROOT / rel
        if p.is_file() and rel not in write:
            optional.append((f"Rust (read-only outline): {rel}", f"```rust\n{rust_outline(p.read_text())}```\n"))
    # Example cases, failing ones first.
    results = last_results()
    outcomes = {c["id"]: c for c in results["cases"]} if results else {}
    cases = case_dirs(ctx.get("cases", []))
    cases.sort(key=lambda d: outcomes.get(d.relative_to(FIXTURES).as_posix(), {}).get("outcome") == "pass")
    for d in cases[: ctx.get("max_examples", 3)]:
        cid = d.relative_to(FIXTURES).as_posix()
        parts = [f"run: `{(d / 'case.yaml').read_text().split('run:')[1].split('expect:')[0].strip()}`\n"]
        if cid in outcomes:
            parts.append(f"current outcome: {outcomes[cid]['outcome']} {outcomes[cid]['detail']}\n")
        for f in sorted((d / "input").rglob("*")) if (d / "input").exists() else []:
            if f.is_file():
                parts.append(f"input/{f.relative_to(d / 'input').as_posix()}:\n```yaml\n{f.read_text()}```\n")
        for name in ("expected.yaml", "expected-error.txt"):
            if (d / name).exists():
                parts.append(f"{name}:\n```\n{(d / name).read_text()}```\n")
        optional.append((f"Example case {cid}", "".join(parts)))
    if len(cases) > ctx.get("max_examples", 3):
        rest = [d.relative_to(FIXTURES).as_posix() for d in cases[ctx.get("max_examples", 3):]]
        optional.append(("Other cases", "Run `just case <id>` for any of: " + ", ".join(rest) + "\n"))

    out = "\n".join(must)
    used = est_tokens(out)
    skipped = []
    for title, body in optional:
        section = f"\n## {title}\n\n{body}"
        cost = est_tokens(section)
        if used + cost <= budget:
            out += section
            used += cost
        elif used + 400 < budget and title.startswith(("Upstream", "Rust")):
            # Truncate a large source rather than drop it.
            keep = int((budget - used - 200) * 3.5)
            out += f"\n## {title} (truncated)\n\n{body[:keep]}\n... [truncated to fit the budget]\n"
            used = budget
        else:
            skipped.append(title)
    if skipped:
        out += "\n## Left out to fit the budget\n\n" + "\n".join(f"- {s}" for s in skipped) + "\n"
    return out


def cmd_brief(args):
    task = get_task(args.task)
    text = build_brief(task, args.budget or task.get("context", {}).get("budget", 12000))
    if args.out:
        Path(args.out).write_text(text)
        print(f"wrote {args.out} (~{est_tokens(text)} tokens)")
    else:
        print(text)


def cmd_workspace(args):
    task = get_task(args.task)
    ws = workspace_path(task["id"])
    if ws.exists():
        shutil.rmtree(ws)
    shutil.copytree(ROOT, ws, ignore=shutil.ignore_patterns(*SKIP_DIRS))
    base_path(ws).parent.mkdir(parents=True, exist_ok=True)
    base_path(ws).write_text(json.dumps(tree_files(ws), sort_keys=True))
    if task.get("status") == "todo":
        set_status(task, "in-progress")
    print(ws)


def gate_scope(task: dict, changes: dict[str, str]) -> list[str]:
    allowed = task.get("scope", {}).get("write", [])
    problems = []
    for rel, kind in changes.items():
        if not matches(rel, allowed):
            problems.append(f"{kind} {rel}: outside the task's scope")
        elif matches(rel, PROTECTED) and rel not in allowed:
            problems.append(f"{kind} {rel}: protected path")
    return problems


def gate_attribution(task: dict, ws: Path, changes: dict[str, str]) -> list[str]:
    if not task.get("context", {}).get("upstream"):
        return []
    # A new file either carries the attribution header or says it isn't ported;
    # the reviewer checks the claim.
    markers = ("ported from", "not ported from upstream")
    return [f"{rel}: new file needs the attribution header (or `// Original code, not ported from upstream.`)"
            for rel, kind in changes.items()
            if kind == "added" and rel.startswith("src/") and rel.endswith(".rs")
            and not any(m in (ws / rel).read_text()[:600] for m in markers)]


def first_lines(text: str, pattern: str, n: int) -> str:
    hits = [l for l in text.splitlines() if re.search(pattern, l)]
    return "\n".join(hits[:n])


def cmd_check(args):
    task = get_task(args.task)
    ws = Path(args.dir) if args.dir else workspace_path(task["id"])
    if not ws.exists():
        die(f"no workspace at {ws}; run `krs workspace {task['id']}`")
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    run_dir = KRS / "runs" / task["id"] / stamp
    run_dir.mkdir(parents=True, exist_ok=True)
    reasons, feedback = [], []
    acc = task.get("accept", {})

    changes = changed_files(ws)
    if not changes:
        reasons.append("no changes")
    reasons += gate_scope(task, changes)
    reasons += gate_attribution(task, ws, changes)

    env = cargo_env(ws)
    code, out = run(["cargo", "fmt", "--", "--check"], ws, run_dir / "fmt.log", env)
    if code:
        reasons.append("cargo fmt --check failed (run `cargo fmt`)")
    code, out = run(["cargo", "clippy", "--all-targets", "--all-features", "--", "-D", "warnings"], ws, run_dir / "clippy.log", env)
    if code:
        reasons.append("clippy failed")
        feedback.append("clippy:\n" + first_lines(out, r"^(error|warning)|-->", 30))
    tests_ok = code == 0
    code, out = run(["cargo", "test", "--all-features"], ws, run_dir / "test.log", env)
    if code:
        reasons.append("cargo test failed")
        failed = re.findall(r"^test (\S+) \.\.\. FAILED", out, re.M)
        feedback.append("failing tests: " + (", ".join(failed) or "(build failed)") + "\n"
                        + first_lines(out, r"^error|panicked at|assertion|left:|right:|-->", 40))
        tests_ok = False
    passed_tests = re.findall(r"^test (\S+) \.\.\. ok", out, re.M)
    for filt in acc.get("tests", []):
        if not any(filt in t for t in passed_tests):
            reasons.append(f"no passing unit test matches `{filt}`")

    results_path = run_dir / "conformance.json"
    code, out = conformance(ws, results_path)
    (run_dir / "conformance.log").write_text(out)
    new_passes, summary = [], {}
    if results_path.exists():
        res = json.loads(results_path.read_text())
        summary = res["summary"]
        baseline = set((ws / "conformance/baseline.txt").read_text().split())
        outcome = {c["id"]: c for c in res["cases"]}
        new_passes = [c for c, v in outcome.items() if v["outcome"] == "pass" and c not in baseline]
        for prefix in acc.get("cases", []):
            missing = [c for c, v in outcome.items() if c.startswith(prefix) and v["outcome"] != "pass"]
            if missing:
                reasons.append(f"{len(missing)} cases under {prefix} don't pass")
                feedback.append("\n".join(f"{c}: {outcome[c]['outcome']} {outcome[c]['detail']}" for c in missing[:8]))
        if len(new_passes) < acc.get("min_new_passes", 0):
            reasons.append(f"{len(new_passes)} newly passing cases, need {acc['min_new_passes']}")
    if code == 2:
        lost = re.findall(r"^  (\S+ \(\w+\))", out, re.M)
        reasons.append(f"conformance regressions: {len(lost)}")
        feedback.append("regressed cases: " + ", ".join(lost[:15]))
    elif code and tests_ok:
        reasons.append("conformance run failed to build or crashed")
        feedback.append(out[-1500:])

    verdict = {
        "task": task["id"], "verdict": "REJECT" if reasons else "ACCEPT", "reasons": reasons,
        "changes": changes, "new_passes": new_passes, "summary": summary,
        "workspace": str(ws), "tree": hashlib.sha256(json.dumps(tree_files(ws), sort_keys=True).encode()).hexdigest(),
        "logs": str(run_dir), "feedback": "\n\n".join(f for f in feedback if f.strip()),
    }
    (run_dir / "verdict.json").write_text(json.dumps(verdict, indent=2))
    (KRS / "runs" / task["id"] / "latest.json").write_text(json.dumps(verdict, indent=2))
    if results_path.exists() and not args.dir:
        shutil.copy(results_path, KRS / "results.json")

    print(f"{verdict['verdict']} {task['id']}: {len(changes)} files changed, {len(new_passes)} cases newly pass"
          + (f", score {summary['pass']}/{summary['inScope']}" if summary else ""))
    for r in reasons[:12]:
        print(f"  - {r}")
    if args.feedback and verdict["feedback"]:
        print("\n" + verdict["feedback"][:4000])
    print(f"  details: {run_dir.relative_to(ROOT)}/verdict.json")
    return verdict


def cmd_accept(args):
    task = get_task(args.task)
    latest = KRS / "runs" / task["id"] / "latest.json"
    if not latest.exists():
        die(f"run `krs check {task['id']}` first")
    verdict = json.loads(latest.read_text())
    ws = Path(verdict["workspace"])
    if verdict["verdict"] != "ACCEPT" and not args.force:
        die("last check was REJECT; fix it, or pass --force if a human reviewed it")
    current = hashlib.sha256(json.dumps(tree_files(ws), sort_keys=True).encode()).hexdigest()
    if current != verdict["tree"]:
        die("the workspace changed since the last check; run `krs check` again")
    changes = changed_files(ws)
    # Refuse to overwrite repo files that changed since the workspace was made:
    # copying would silently undo that work.
    base, repo_now = base_files(ws), tree_files(ROOT)
    conflicts = [rel for rel in changes if repo_now.get(rel) != base.get(rel)]
    if conflicts:
        die("these files changed in the repo since the workspace was created; merge by hand "
            "or recreate the workspace and redo the change:\n  " + "\n  ".join(conflicts))
    patch_dir = KRS / "patches"
    patch_dir.mkdir(parents=True, exist_ok=True)
    patch = patch_dir / f"{task['id']}.patch"
    diff = []
    for rel in changes:
        before = (ROOT / rel).read_text().splitlines(keepends=True) if (ROOT / rel).exists() else []
        after = (ws / rel).read_text().splitlines(keepends=True) if (ws / rel).exists() else []
        diff += difflib.unified_diff(before, after, f"a/{rel}", f"b/{rel}")
    patch.write_text("".join(diff))
    for rel, kind in changes.items():
        if kind == "deleted":
            (ROOT / rel).unlink(missing_ok=True)
        else:
            (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ws / rel, ROOT / rel)
    code, out = run(["cargo", "test", "-q", "--test", "conformance", "--", "--write-baseline"], ROOT, env=cargo_env(ROOT))
    if code:
        die(f"files were copied, but the baseline run failed; fix and run `just baseline`:\n{out[-1500:]}")
    print(next((l for l in out.splitlines() if "baseline.txt" in l), "baseline not written?"))
    set_status(task, "done")
    log("accept", task["id"], f"{len(changes)} files, {len(verdict['new_passes'])} new passes")
    shutil.rmtree(ws, ignore_errors=True)
    shutil.rmtree(ROOT / "target/krs" / ws.name, ignore_errors=True)
    base_path(ws).unlink(missing_ok=True)
    print(f"accepted {task['id']}: {len(changes)} files copied into the repo; patch at {patch.relative_to(ROOT)}")
    print("next: review `git diff`, run `just ci`, and commit (humans commit; agents don't)")


def cmd_reject(args):
    task = get_task(args.task)
    log("reject", task["id"], args.reason or "")
    ws = workspace_path(task["id"])
    if ws.exists() and not args.keep:
        shutil.rmtree(ws)
        shutil.rmtree(ROOT / "target/krs" / ws.name, ignore_errors=True)
        base_path(ws).unlink(missing_ok=True)
    if task.get("status") == "in-progress":
        set_status(task, "todo")
    print(f"rejected {task['id']}" + (f": {args.reason}" if args.reason else ""))


def log(action: str, task_id: str, note: str):
    KRS.mkdir(parents=True, exist_ok=True)
    with (KRS / "log.jsonl").open("a") as f:
        f.write(json.dumps({"time": dt.datetime.now().isoformat(timespec="seconds"),
                            "action": action, "task": task_id, "note": note}) + "\n")


